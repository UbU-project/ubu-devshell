// Preserves the standing offline guard's fixture cases; no Python dependency.
import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
const [generator, tool] = process.argv.slice(2).map((argument) => resolve(argument));
const marker = "# Generated by ubu-devshell/scripts/gen-patch-config.sh";
const temp = mkdtempSync(join(tmpdir(), "ubu-patch-test-"));
const root = join(temp, "siblings with spaces");
function write(path, text) { mkdirSync(dirname(path), { recursive: true }); writeFileSync(path, text); }
function pkg(directory, name, extra = "") {
  write(join(directory, "Cargo.toml"), `[package]\nname = "${name}"\nversion = "0.1.0"\nedition = "2021"\n${extra}`);
  write(join(directory, "src/lib.rs"), "");
}
const runOptions = { encoding: "utf8", timeout: 60000, env: { ...process.env, CARGO_NET_OFFLINE: "true" } };
function git(directory, ...args) { return execFileSync("git", ["-C", directory, ...args], runOptions); }
try {
  mkdirSync(root);
  const reposFile = join(root, "repos.toml");
  write(reposFile, `[repos]
consumer = "https://example.invalid/consumer"
root_sibling = "https://example.invalid/root"
workspace_sibling = "https://example.invalid/workspace"
unused_sibling = "https://example.invalid/unused"
absent_sibling = "https://example.invalid/absent"
no_dependencies = "https://example.invalid/no-dependencies"
workspace_consumer = "https://example.invalid/workspace-consumer"
`);
  pkg(join(root, "root-sibling"), "actual_root");
  const workspace = join(root, "workspace-sibling");
  write(join(workspace, "Cargo.toml"), '[workspace]\nresolver = "2"\nmembers = ["modules/*"]\n');
  pkg(join(workspace, "modules/alpha"), "actual_alpha");
  pkg(join(workspace, "modules/beta"), "actual_beta");
  write(join(root, "unused-sibling/Cargo.toml"), "[workspace]\nmembers = []\n");
  pkg(join(root, "no-dependencies"), "no_dependencies");
  const consumer = join(root, "consumer");
  pkg(consumer, "consumer", `
[dependencies]
root_alias = { package = "actual_root", git = "https://example.invalid/root" }
alpha_alias = { package = "actual_alpha", git = "https://example.invalid/workspace" }
absent = { git = "https://example.invalid/absent" }
unlisted = { git = "https://example.invalid/unlisted" }
[dev-dependencies]
actual_beta = { git = "https://example.invalid/workspace" }
[build-dependencies]
another_alpha = { package = "actual_alpha", git = "https://example.invalid/workspace" }
[target.'cfg(unix)'.dependencies]
target_root = { package = "actual_root", git = "https://example.invalid/root" }
`);
  const wc = join(root, "workspace-consumer");
  write(join(wc, "Cargo.toml"), `[workspace]
resolver = "2"
members = ["member"]
[workspace.dependencies]
root_alias = { package = "actual_root", git = "https://example.invalid/root" }
`);
  pkg(join(wc, "member"), "member", `[dependencies]
root_alias.workspace = true
[build-dependencies]
beta_alias = { package = "actual_beta", git = "https://example.invalid/workspace" }
`);
  git(consumer, "init", "-q");
  write(join(consumer, ".gitignore"), ".cargo/config.toml\n");
  git(join(root, "no-dependencies"), "init", "-q");
  const config = join(consumer, ".cargo/config.toml");
  const stale = join(root, "no-dependencies/.cargo/config.toml");
  write(stale, marker + '\n[patch."https://example.invalid/old"]\nold = { path = "../old" }\n');
  write(join(workspace, ".cargo/config.toml"), marker + '\n[patch."https://example.invalid/bad"]\nbad = { path = "../unused-sibling" }\n');
  const env = { ...runOptions.env, REPOS_DIR: root, REPOS_FILE: reposFile };
  function generate(ok = true) {
    const result = spawnSync("bash", [generator], { ...runOptions, cwd: root, env });
    if (result.error) throw result.error;
    assert.equal(result.status === 0, ok, result.stdout + result.stderr);
    return result.stdout + result.stderr;
  }
  function parsed(path) { return JSON.parse(execFileSync(tool, ["parse", path], runOptions)).patch; }
  let output = generate();
  assert.ok(output.includes("Files written:"));
  const legacyBytes = marker + '\n# Local-only Cargo patches. Do not commit this file.\n# Re-run from ubu-devshell when sibling paths change.\n\n' +
    '[patch."https://example.invalid/root"]\nactual_root = { path = "../root-sibling" }\n\n' +
    '[patch."https://example.invalid/workspace"]\nactual_alpha = { path = "../workspace-sibling/modules/alpha" }\nactual_beta = { path = "../workspace-sibling/modules/beta" }\n';
  assert.equal(readFileSync(config, "utf8"), legacyBytes, "full generator output remains byte-identical to its existing fixture contract");
  const patches = parsed(config);
  assert.deepEqual(patches["https://example.invalid/root"], { actual_root: { path: "../root-sibling" } });
  console.log("PASS package-root dependency uses the actual package name and root directory");
  assert.deepEqual(patches["https://example.invalid/workspace"], {
    actual_alpha: { path: "../workspace-sibling/modules/alpha" }, actual_beta: { path: "../workspace-sibling/modules/beta" }
  });
  assert.equal(readFileSync(config, "utf8").split('[patch."https://example.invalid/workspace"]').length - 1, 1);
  console.log("PASS virtual workspace aliases resolve two packages under one URL block");
  for (const name of readdirSync(root)) {
    const path = join(root, name, ".cargo/config.toml");
    if (existsSync(path)) { const text = readFileSync(path, "utf8"); assert.ok(!text.includes("https://example.invalid/unused")); assert.ok(!text.includes("unused_sibling")); }
  }
  console.log("PASS unused sibling emits no patch entry");
  assert.ok(!Object.hasOwn(patches, "https://example.invalid/absent")); assert.ok(!Object.hasOwn(patches, "https://example.invalid/unlisted"));
  console.log("PASS absent and unlisted git siblings are skipped offline");
  assert.ok(!existsSync(stale)); assert.ok(!existsSync(join(root, "root-sibling/.cargo/config.toml")));
  console.log("PASS dependency-free consumers get no file and stale marked files are removed");
  const workspacePatches = parsed(join(wc, ".cargo/config.toml"));
  assert.ok(Object.hasOwn(workspacePatches["https://example.invalid/root"], "actual_root"));
  assert.ok(Object.hasOwn(workspacePatches["https://example.invalid/workspace"], "actual_beta"));
  console.log("PASS workspace inheritance, member, target, dev and build dependency tables");
  const original = readFileSync(config); const mtime = statSync(config, { bigint: true }).mtimeNs;
  output = generate(); assert.ok(output.includes(`unchanged: ${config}`)); assert.ok(output.includes("No files written."));
  assert.deepEqual(readFileSync(config), original); assert.equal(statSync(config, { bigint: true }).mtimeNs, mtime);
  console.log("PASS repeat generation preserves bytes, mtime and unchanged reporting");
  git(consumer, "add", "-f", ".cargo/config.toml"); assert.ok(generate(false).includes("is tracked")); assert.deepEqual(readFileSync(config), original);
  git(consumer, "rm", "--cached", "-f", ".cargo/config.toml");
  console.log("PASS tracked config is refused without modification");
  write(config, "# operator config\n"); assert.ok(generate(false).includes("without the ubu-devshell generated marker")); assert.equal(readFileSync(config, "utf8"), "# operator config\n");
  writeFileSync(config, original); write(stale, "# operator config in dependency-free consumer\n");
  assert.ok(generate(false).includes("without the ubu-devshell generated marker")); assert.equal(readFileSync(stale, "utf8"), "# operator config in dependency-free consumer\n"); unlinkSync(stale);
  console.log("PASS unmarked configs are refused, including dependency-free consumers");
  const manifest = join(consumer, "Cargo.toml"); const text = readFileSync(manifest, "utf8");
  write(manifest, text.replace('package = "actual_root"', 'package = "missing_package"'));
  assert.ok(generate(false).includes("package missing_package not found")); assert.deepEqual(readFileSync(config), original); write(manifest, text);
  console.log("PASS missing package fails without overwriting the consumer config");
  unlinkSync(join(consumer, ".gitignore")); assert.ok(generate().includes(`warn: ${consumer} should ignore .cargo/config.toml`));
  console.log("PASS gitignore warning is preserved");
  console.log("PASS test-patch-config.sh (isolated offline fixtures)");
} finally { rmSync(temp, { recursive: true, force: true }); }
